import { createHash, randomBytes } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import {
  bytesToHex,
  concatBytes,
  patternBytes,
  utf8Bytes,
} from '../src/platform/bytes'
import { randomHex, randomUint32 } from '../src/platform/random'
import { sha256 } from '../src/platform/sha256'
import { hashUid } from '../src/syntheticFixtures/uid'

const referenceSha256 = (input: string | Uint8Array) =>
  createHash('sha256').update(input).digest('hex')

describe('sha256 — differential against node:crypto', () => {
  it('matches on the classic vectors', () => {
    for (const input of ['', 'abc', 'a'.repeat(1_000_000)]) {
      expect(bytesToHex(sha256(input))).toBe(referenceSha256(input))
    }
  })

  it('matches across the padding-boundary lengths', () => {
    // 55/56/57 and 63/64/65 straddle where the length field and the 0x80
    // padding byte spill into an extra block.
    for (const n of [1, 31, 32, 54, 55, 56, 57, 63, 64, 65, 119, 120, 128]) {
      const str = 'a'.repeat(n)
      expect(bytesToHex(sha256(str))).toBe(referenceSha256(str))
      const bytes = new Uint8Array(randomBytes(n))
      expect(bytesToHex(sha256(bytes))).toBe(referenceSha256(bytes))
    }
  })

  it('matches on unicode input', () => {
    const input = 'salt‖key — ünïcodé ✓ 汉字'
    expect(bytesToHex(sha256(input))).toBe(referenceSha256(input))
  })

  it('matches on hashUid-shaped inputs', () => {
    for (let i = 0; i < 200; i++) {
      const input = `${randomBytes((i % 40) + 1).toString('hex')} sop:${i}`
      expect(bytesToHex(sha256(input))).toBe(referenceSha256(input))
    }
  })
})

describe('hashUid — unchanged by the vendored digest', () => {
  it('still produces the exact UIDs the node:crypto implementation did', () => {
    // Pinned from the node:crypto implementation — guards UID stability for
    // salted datasets generated by earlier releases.
    expect(hashUid('seed:1', 'sop:0')).toBe(
      '2.25.71468702425797452419811470950363380328',
    )
    expect(hashUid('a-salt', 'study:0')).toBe(
      '2.25.270009024586409588027740363663384520750',
    )
  })

  it('matches a node:crypto reference across many (salt, key) pairs', () => {
    for (let i = 0; i < 100; i++) {
      const salt = `seed:${i}`
      const key = `series:${i}:${i % 3}`
      const digest = createHash('sha256')
        .update(salt)
        .update(' ')
        .update(key)
        .digest()
      const expected = `2.25.${BigInt(`0x${digest.subarray(0, 16).toString('hex')}`).toString()}`
      expect(hashUid(salt, key)).toBe(expected)
    }
  })
})

describe('platform random', () => {
  it('randomUint32 returns integers in [0, 2^32)', () => {
    for (let i = 0; i < 100; i++) {
      const n = randomUint32()
      expect(Number.isInteger(n)).toBe(true)
      expect(n).toBeGreaterThanOrEqual(0)
      expect(n).toBeLessThan(0x100000000)
    }
  })

  it('randomHex returns lowercase hex of the requested byte length', () => {
    const hex = randomHex(16)
    expect(hex).toMatch(/^[0-9a-f]{32}$/)
    expect(randomHex(16)).not.toBe(hex)
  })
})

describe('platform bytes', () => {
  it('bytesToHex matches Buffer hex encoding', () => {
    const bytes = new Uint8Array(randomBytes(64))
    expect(bytesToHex(bytes)).toBe(Buffer.from(bytes).toString('hex'))
  })

  it('utf8Bytes matches Buffer utf8 encoding', () => {
    const text = 'not dicom — ünïcodé 汉字'
    expect(Buffer.from(utf8Bytes(text))).toEqual(Buffer.from(text, 'utf8'))
  })

  it('concatBytes joins parts in order', () => {
    const joined = concatBytes(
      new Uint8Array([1, 2]),
      new Uint8Array([]),
      new Uint8Array([3]),
    )
    expect(Array.from(joined)).toEqual([1, 2, 3])
  })

  it('patternBytes matches Buffer.alloc pattern fill, including truncation', () => {
    for (const length of [0, 1, 9, 10, 11, 1024, 4096 + 7]) {
      expect(Buffer.from(patternBytes(length, 'not dicom '))).toEqual(
        Buffer.alloc(length, 'not dicom '),
      )
    }
  })

  it('patternBytes with an empty pattern yields zeros', () => {
    expect(Array.from(patternBytes(4, ''))).toEqual([0, 0, 0, 0])
  })
})
